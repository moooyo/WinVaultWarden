"""Render MRT Core resources and typed string keys from an approved catalog.

Run only in an authorized verification environment. Translation maps are data files,
and source files are never inferred from visible user content at runtime.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
import re
import xml.etree.ElementTree as ET


def load_json(path: Path):
    return json.loads(path.read_text(encoding="utf-8-sig"))


def load_translations(directory: Path, language: str) -> dict[str, str]:
    translated: dict[str, str] = {}
    for path in sorted(directory.glob(f"{language}*.json")):
        for source, value in load_json(path).items():
            if not isinstance(value, str):
                raise ValueError(f"Translation is not a string: {path.name}: {source!r}")
            if source in translated and translated[source] != value:
                raise ValueError(f"Conflicting translations: {path.name}: {source!r}")
            translated[source] = value
    return translated


def format_items(value: str) -> list[str]:
    # Treat doubled braces as literals and compare full composite format items,
    # including alignment and formatting, to preserve numeric/date presentation.
    sanitized = value.replace("{{", "").replace("}}", "")
    return sorted(re.findall(r"\{\d+(?:,-?\d+)?(?::[^{}]*)?\}", sanitized))


def localize_date_formats(value: str, language: str) -> str:
    if language != "en-US":
        return value

    def replace(match: re.Match[str]) -> str:
        date_format = match.group(2)
        for original, localized in (
            ("yyyy 年 M 月 d 日", "MMM d, yyyy"),
            ("M 月 d 日", "MMM d"),
            ("yyyy 年 M 月", "MMM yyyy"),
            ("yyyy年M月d日", "MMM d, yyyy"),
            ("M月d日", "MMM d"),
            ("yyyy年M月", "MMM yyyy"),
        ):
            date_format = date_format.replace(original, localized)
        return match.group(1) + date_format + "}"

    return re.sub(r"(\{\d+(?:,-?\d+)?:)([^{}]*)(\})", replace, value)


def write_resw(path: Path, values: dict[str, str], comments: dict[str, str]) -> None:
    root = ET.Element("root")
    for name, value in (
        ("resmimetype", "text/microsoft-resx"),
        ("version", "2.0"),
        ("reader", "System.Resources.ResXResourceReader, System.Windows.Forms"),
        ("writer", "System.Resources.ResXResourceWriter, System.Windows.Forms"),
    ):
        header = ET.SubElement(root, "resheader", {"name": name})
        ET.SubElement(header, "value").text = value
    for key in sorted(values):
        item = ET.SubElement(root, "data", {"name": key, "{http://www.w3.org/XML/1998/namespace}space": "preserve"})
        ET.SubElement(item, "value").text = values[key]
        if key in comments:
            ET.SubElement(item, "comment").text = comments[key]
    ET.indent(root, space="  ")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(ET.tostring(root, encoding="unicode", xml_declaration=True) + "\n", encoding="utf-8")


def render(repo: Path, catalog_file: Path) -> None:
    catalog = load_json(catalog_file)
    texts = {entry["Key"]: entry for entry in catalog["Texts"]}
    translation_dir = repo / "src/App/Localization/Translations"
    translations = {
        "zh-CN": {
            **{entry["Source"]: entry["Source"] for entry in texts.values()},
            **load_translations(translation_dir, "zh-CN"),
        },
        **{language: load_translations(translation_dir, language)
           for language in ("zh-TW", "en-US", "ja-JP")},
    }
    missing: list[str] = []
    for language, translated in translations.items():
        for entry in texts.values():
            source = entry["Source"]
            if source not in translated:
                missing.append(f"{language}: {entry['Key']}: {source}")
                continue
            translated[source] = localize_date_formats(translated[source], language)
            if format_items(localize_date_formats(source, language)) != format_items(translated[source]):
                raise ValueError(f"Format item mismatch for {language}: {entry['Key']}")
    if missing:
        raise ValueError("Missing translations:\n" + "\n".join(missing))

    fallback = {key: translations["zh-CN"][entry["Source"]] for key, entry in sorted(texts.items())}
    fallback_path = repo / "src/App/Localization/DefaultResources.json"
    fallback_path.write_text(json.dumps(fallback, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    keys = ["// <auto-generated />", "namespace App.Localization;", "", "public enum UiStringKey", "{"]
    keys.extend(f"    {key}," for key in sorted(texts))
    keys.append("}")
    (repo / "src/App/Localization/UiStringKey.g.cs").write_text("\n".join(keys) + "\n", encoding="utf-8")

    comments: dict[str, str] = {}
    for key, entry in texts.items():
        contexts = entry.get("Contexts", [])
        comments[key] = "Source context: " + "; ".join(
            f"{item['File']}:{item['Line']}" for item in contexts[:5])
    for language, translated in translations.items():
        values = {key: translated[entry["Source"]] for key, entry in texts.items()}
        resource_comments = dict(comments)
        for element in catalog["XamlElements"]:
            if element["Element"].split(":")[-1] == "Window":
                continue
            for property_info in element["Properties"]:
                key = property_info["ResourceName"]
                value = translated[property_info["Source"]]
                if key in values and values[key] != value:
                    raise ValueError(f"Conflicting XAML resource: {key}")
                values[key] = value
                resource_comments[key] = f"Source XAML: {element['File']} ({element['Element']})"
        write_resw(repo / "src/App/Strings" / language / "Resources.resw", values, resource_comments)
    print(f"Rendered {len(texts)} typed resources for {len(translations)} languages.")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("repository", type=Path)
    parser.add_argument("catalog", type=Path)
    arguments = parser.parse_args()
    render(arguments.repository.resolve(), arguments.catalog.resolve())
